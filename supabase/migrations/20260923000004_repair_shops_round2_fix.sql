-- 2026-09-23 수리점 2차 조사 반영분 두 건을 바로잡는다.
--
-- 홍성중앙카메라의 조양로 7 은 운영자가 직접 확인해 준 값이라 그대로 둔다.

-- ── 1. 작은풍경: 도로명 주소로 ──
-- 20260923000003 이 넣은 값이 지번 주소('인의동 112-2')였다. 이 사이트는
-- 도로명으로 적는다. 주소가 네이버 지도 검색 링크와 LocalBusiness 구조화
-- 데이터에 그대로 들어가기 때문이다.
-- 운영자가 확인해 준 도로명은 창경궁로 109 다. 세운스퀘어는 세운상가 가동의
-- 지금 이름이라 features 의 '세운상가 1층' 과 어긋나지 않는다.
update public.repair_shops
   set address = '서울 종로구 창경궁로 109 세운스퀘어 테크노관 148호'
 where name = '작은풍경'
   and region = '서울'
   and address = '서울 종로구 인의동 112-2 세운스퀘어 테크노관 148호';

-- ── 2. 한국카메라AS: 설명을 되돌린다 ──
-- 20260923000003 이 "과거 한국카메라AS에서 이어진 핫셀블라드 수리처로
-- 알려졌지만…" 으로 바꿨다. 항목 이름이 한국카메라AS 인데 설명이 자기
-- 자신을 가리켜, 읽는 사람이 무슨 말인지 알 수 없다.
-- 원래 문장이 같은 사실을 더 분명하게 말한다. 틀렸다는 근거도 없다.
update public.repair_shops
   set description = '폐업 후 일산에서 소규모로 다시 시작. 핫셀블라드 전문.'
 where name = '한국카메라AS'
   and region = '경기'
   and description = '과거 한국카메라AS에서 이어진 핫셀블라드 수리처로 알려졌지만, 최근 접수 여부는 확인이 필요하다.';
