-- 부산 신카메라의 주소 표기를 나머지와 맞춘다.
--
-- 20260923000001 이 넣은 값이 '부산광역시 중구 …' 였다. 이 사이트는 주소의
-- 시·도를 줄여 쓴다. 현상소 96곳 가운데 95곳이 '부산 중구', '서울 중구'
-- 식이고 수리점도 나머지가 모두 그렇다.
--
-- 표기가 갈리면 보기에만 어색한 것이 아니다. 이 값이 네이버 지도 검색
-- 링크(map.naver.com/p/search/<주소>)에 그대로 들어가고, 지역 페이지의
-- LocalBusiness 구조화 데이터에도 streetAddress 로 실린다.
--
-- 지번동('남포동2가')과 도로명('남포길 47')이 섞여 있는 것은 그대로 둔다.
-- 조사에서 확인된 표기가 그러했고, 어느 쪽이 맞는지 확인하지 못했다.
-- 다음 조사로 넘긴다.
--
-- 옛 값을 조건에 넣어 재실행(replay)에 안전하게 만든다.

update public.repair_shops
   set address = '부산 중구 남포동2가 남포길 47'
 where name = '부산 신카메라'
   and region = '부산'
   and address = '부산광역시 중구 남포동2가 남포길 47';
